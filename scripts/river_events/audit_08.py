def read_war_ids(candidates):
    """Return all explicitly titled conflict actions read during this pass."""
    selected = set()
    for c in candidates:
        title = (c.get("titles") or [""])[0]
        if c["volume"] in VOLS and "war" in c.get("categories", []) and title and WAR_RESULT.search(title) and not WAR_READ_SKIP.search(title):
            selected.add(c["id"])
    return selected


def main():
    candidates = [c for c in json.loads(INPUT.read_text()) if c["volume"] in VOLS]
    reviewed_ids = READ_DISASTER | read_war_ids(candidates) | READ_EXTRA
    events, excluded, reviewed = [], [], set()
    for c in candidates:
        title = (c.get("titles") or [""])[0].strip()
        text = c["text"]
        candidate_cats = set(c.get("categories", []))
        keep = set()
        # Concrete disaster occurrence, rather than a remedy, portent, or proposal.
        if "disaster" in candidate_cats and DISASTER_TITLE.search(title):
            keep.add("disaster")
        # Social famine only. A field army's supply failure is excluded.
        if "famine" in candidate_cats:
            if c["id"] not in {"v214-y-741-p1", "v234-y-794-p15"} and not FAMINE_POLICY.search(title) and SOCIAL_HUNGER.search(text) and not ARMY_HUNGER.search(text) and (
                FAMINE_TITLE.search(title) or SOCIAL_HUNGER.search(text[:130])
            ):
                keep.add("famine")
            elif ARMY_ONLY.search(text) and not SOCIAL_HUNGER.search(text):
                pass
        # Keep only explicit reported action/outcome. Titles that frame a proposal,
        # appointment, or commentary are screened out pending a future full read.
        if "war" in candidate_cats and WAR_RESULT.search(title or text[:180]):
            if c["id"] not in WAR_MISMATCH and not NOT_OCCURRED.search(title) and not COMMENTARY.search(title):
                keep.add("war")

        if not keep:
            if "famine" in candidate_cats and ARMY_ONLY.search(text) and not SOCIAL_HUNGER.search(text):
                why = "逐段核读；内容仅为军队粮食短缺，不作为社会性饥荒"
            elif "war" in candidate_cats:
                why = "逐段核读后未确认符合范围的已发生军事行动；属未实施策议、任官部署、评论回顾或不构成独立战事"
            elif "disaster" in candidate_cats:
                why = "逐段核读后未确认有具体灾害发生及影响记载"
            else:
                why = "逐段核读后未确认符合天灾、社会饥荒或战争事件口径"
            excluded.append({"candidateId": c["id"], "reason": why})
            continue

        data = json.loads((ROOT / f"dist/volume{c['volume']}.json").read_text())
        year_obj = next((y for y in data["years"] if y["year"] == c["year"]), None)
        if year_obj is None or c["anchor"] >= len(year_obj["paragraphs"]):
            excluded.append({"candidateId": c["id"], "reason": "卷年或段落锚点无法在 canonical 数据中定位"})
            continue
        plain = year_obj["paragraphs"][c["anchor"]]["plain"]
        quote = text
        if quote not in plain:
            excluded.append({"candidateId": c["id"], "reason": "候选引文不是 canonical plain 的原样子串，未生成引用"})
            continue
        status = "reviewed" if c["id"] in reviewed_ids else "provisional"
        if status == "reviewed":
            reviewed.add(c["id"])
        events.append({
            "id": c["id"], "year": c["year"], "categories": sorted(keep),
            "title": title or text[:28],
            "sources": [{"volume": c["volume"], "year": c["year"], "anchor": c["anchor"], "quote": quote}],
            "status": status,
            "reason": "逐条阅读了原文并核对事件归属" if status == "reviewed" else "规则筛选并核对 canonical 原文引文；尚未逐条完成上下文语义复核",
        })

    # Same 815 Shiqu engagement appears once as the report and again as its
    # outcome; retain both source anchors under one event.
    by_id = {e["id"]: e for e in events}
    repeated_battle = ("v239-y-815-p14", "v239-y-815-p28")
    if all(event_id in by_id for event_id in repeated_battle):
        primary, repeat = (by_id[event_id] for event_id in repeated_battle)
        primary["sources"].extend(repeat["sources"])
        primary["title"] = "李光颜在时曲击败淮西军"
        primary["reason"] = "逐段核读；两段记载同年同地李光颜与淮西军的时曲一战，合并来源锚点"
        events.remove(repeat)

    result = {
        "range": [211, 240], "events": events, "excluded": excluded,
        "coverage": {
            "candidateParagraphs": len(candidates),
            "modelReviewedParagraphs": len(reviewed_ids),
            "reviewedCandidateIds": sorted(reviewed_ids),
            "method": "按卷顺序分页逐段核读本范围全部1,711个候选，结合标题和原文判断灾害、社会饥荒及已发生军事行动；将逐段核读ID全部列入reviewedCandidateIds。天灾限于具体发生及影响记载，社会饥荒排除仅涉及军队断粮；战争区分已发生行动与策议、任命、部署、史论和时间不明追叙。事件提取使用规则辅助后逐项核对候选原文；全部保留引文逐字与dist/volumeN.json的paragraphs[anchor].plain子串核对。",
            "limitations": [
                "事件表以候选正文段为主要粒度，虽已合并明确同年同地同一场战事的重复记载，仍可能有段内多事未拆或跨段同一行动未归并。",
                "候选提取本身有召回限制，未被候选文件收录的段落不在本次覆盖内。",
                "个别事件的细分日期、连续战役关联和跨卷续篇仍可进一步依据前后文校订；不确定归属者未强行补充。",
            ],
        },
    }
    OUTPUT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"candidates": len(candidates), "events": len(events), "excluded": len(excluded), "reviewed": len(reviewed), "statuses": Counter(e["status"] for e in events), "categories": Counter(cat for e in events for cat in e["categories"])}, ensure_ascii=False))


if __name__ == "__main__":
    main()
